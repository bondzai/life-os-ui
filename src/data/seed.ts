export function seedIfEmpty(): void {
  if (!localStorage.getItem(`${KEY_PREFIX}users`)) {
    localStorage.setItem(`${KEY_PREFIX}users`, JSON.stringify(users))
  }
  if (!localStorage.getItem(`${KEY_PREFIX}entities`)) {
    localStorage.setItem(`${KEY_PREFIX}entities`, JSON.stringify(entities))
  }
  if (!localStorage.getItem(`${KEY_PREFIX}relations`)) {
    localStorage.setItem(`${KEY_PREFIX}relations`, JSON.stringify(relations))
  }
  if (!localStorage.getItem(`${KEY_PREFIX}trackers`)) {
    localStorage.setItem(`${KEY_PREFIX}trackers`, JSON.stringify(trackers))
  }
}
